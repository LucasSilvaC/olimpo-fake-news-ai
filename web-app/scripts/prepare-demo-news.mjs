import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const inputs = JSON.parse(
  await readFile(new URL("./demo-news-inputs.json", import.meta.url), "utf8"),
);
const engine = (process.env.DEMO_MODEL_URL ?? "http://127.0.0.1:8010").replace(/\/$/, "");
const capturedAt = new Date().toISOString();
const fixtures = [];

async function analyze(endpoint, text) {
  const response = await fetch(`${engine}${endpoint}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ text }),
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) throw new Error(`${endpoint}: HTTP ${response.status}`);
  return response.json();
}

for (const input of inputs) {
  const prediction = await analyze("/supervised/analyze", input.content);
  const insights = await analyze("/analyze", input.content);
  if (
    prediction.analysisStatus !== "ok" ||
    prediction.classification !== input.targetClassification
  ) {
    throw new Error(
      `${input.id}: real prediction ${prediction.classification} (${prediction.fakeProbability}) differs from ${input.targetClassification}; existing fixtures untouched`,
    );
  }
  if (!["ok", "no_match"].includes(insights.analysisStatus)) {
    throw new Error(`${input.id}: linguistic analysis unavailable`);
  }
  const families = new Set();
  insights.insights = insights.insights.filter((insight) => {
    if (families.has(insight.redundancyFamily) || families.size >= 3) return false;
    families.add(insight.redundancyFamily);
    return true;
  });
  const { id, targetClassification, explanation, sourceUrl, ...fields } = input;
  fixtures.push({
    id,
    article: {
      ...fields,
      canonicalUrl: fields.url,
      authors: [],
      modifiedAt: null,
      language: "pt-BR",
      extractionMethod: "local",
      usedFallback: false,
    },
    targetClassification,
    prediction,
    insights,
    explanation,
    sourceUrl,
    capturedAt,
    bodySha256: createHash("sha256").update(input.content, "utf8").digest("hex"),
  });
  console.log(
    `${id}: ${prediction.classification} (${(prediction.fakeProbability * 100).toFixed(2)}%); insights=${insights.analysisStatus}`,
  );
}

const source = `// Generated by scripts/prepare-demo-news.mjs from real frozen-model inference.\nimport "server-only";\n\nimport type { AIAnalysisResult } from "@/app/api/ai-feedback/repositories/ai-analysis-service.interface";\nimport type { INewsArticle } from "@/lib/news/types";\nimport type { NewsInsightsAnalysis } from "@/lib/news-insights/types";\nimport type { MLTargetType } from "@/server/shared/database/schemas/enums";\n\nexport interface DemoNewsFixture {\n  id: string;\n  article: INewsArticle;\n  targetClassification: MLTargetType;\n  prediction: AIAnalysisResult;\n  insights: NewsInsightsAnalysis;\n  explanation: string;\n  sourceUrl: string | null;\n  capturedAt: string;\n  bodySha256: string;\n}\n\nexport const demoNewsFixtures: DemoNewsFixture[] = ${JSON.stringify(fixtures, null, 2)};\n\nexport function getDemoNewsFixture(id: string): DemoNewsFixture | undefined {\n  return demoNewsFixtures.find((fixture) => fixture.id === id);\n}\n`;
await writeFile(new URL("../src/server/demo/demo-news.ts", import.meta.url), source, "utf8");
